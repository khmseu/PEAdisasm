OPCODES_65C02: dict[int, Opcode65C02] = {}
for hi, row in enumerate(_ROWS):
    if len(row) != 16:
        raise RuntimeError(f"invalid 65C02 opcode row length at {hi:02X}")
    for lo, (mnemonic, mode) in enumerate(row):
        OPCODES_65C02[(hi << 4) | lo] = _op(mnemonic, mode)

if len(OPCODES_65C02) != 0x100:
    raise RuntimeError("65C02 opcode map must contain 256 entries")
