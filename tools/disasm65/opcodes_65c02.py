from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

AddressingMode65C02 = Literal[
    "imp",
    "acc",
    "imm",
    "rel",
    "abs",
    "absx",
    "absy",
    "ind",
    "iax",
    "zp",
    "zpx",
    "zpy",
    "indx",
    "indy",
    "izp",
    "zprel",
]


@dataclass(frozen=True)
class Opcode65C02:
    mnemonic: str
    mode: AddressingMode65C02
    length: int


_MODE_LENGTHS: dict[AddressingMode65C02, int] = {
    "imp": 1,
    "acc": 1,
    "imm": 2,
    "rel": 2,
    "abs": 3,
    "absx": 3,
    "absy": 3,
    "ind": 3,
    "iax": 3,
    "zp": 2,
    "zpx": 2,
    "zpy": 2,
    "indx": 2,
    "indy": 2,
    "izp": 2,
    "zprel": 3,
}


def _op(mnemonic: str, mode: AddressingMode65C02) -> Opcode65C02:
    return Opcode65C02(mnemonic=mnemonic, mode=mode, length=_MODE_LENGTHS[mode])


